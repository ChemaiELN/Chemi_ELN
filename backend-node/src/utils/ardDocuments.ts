function wrap(title: string, body: string): string {
  const ts = new Date().toLocaleString('en-IN')
  return `<!DOCTYPE html><html><head><meta charset="UTF-8">
  <title>${title}</title>
  <style>${BASE_CSS}</style>
  </head><body>
  ${body}
  <div class="footer">Generated by Laurus ELN &nbsp;·&nbsp; ${ts} &nbsp;·&nbsp; Confidential</div>
  </body></html>`
}

function statusBadge(status: string): string {
  const colors: Record<string, string> = {
    APPROVED: '#166534', SUBMITTED: '#1d4ed8', DRAFT: '#6b7280',
    REJECTED: '#991b1b', PENDING: '#92400e', COMPLETED: '#166534',
    RECEIVED: '#065f46', REGISTERED: '#1e3a8a', WITHDRAWN: '#4b5563',
  }
  const bg = colors[status?.toUpperCase()] ?? '#6b7280'
  return `<span class="badge" style="background:${bg};color:#fff">${status ?? ''}</span>`
}

async function qrDataUri(data: string): Promise<string> {
  return QRCode.toDataURL(data, { width: 80, margin: 1 })
}

async function barcodeDataUri(data: string): Promise<string> {
  try {
    const png = await bwipjs.toBuffer({ bcid: 'code128', text: data, scale: 2, height: 8, includetext: true, textxalign: 'center' })
    return `data:image/png;base64,${png.toString('base64')}`
  } catch {
    return ''
  }
}

// ── ATR Summary ───────────────────────────────────────────────────────────────
export async function atrSummaryHtml(form: any, company = 'Laurus Labs'): Promise<string> {
  const qr = await qrDataUri(`ATR:${form.arNo ?? form.id}`)
  const meta = [
    ['AR No', form.arNo ?? '—'], ['Status', statusBadge(form.status)],
    ['Project Code', form.projectCode ?? '—'], ['Project Name', form.projectName ?? '—'],
    ['Sample Code', form.sampleCode ?? '—'], ['Batch No', form.batchNo ?? '—'],
    ['Submitted By', form.submittedBy ?? '—'], ['Submitted At', form.submittedAt ? new Date(form.submittedAt).toLocaleDateString('en-IN') : '—'],
    ['Priority', form.priority ?? 'NORMAL'], ['Department', form.department ?? '—'],
  ]
  const metaRows = meta.map(([k, v]) => `<tr><td class="label">${k}</td><td>${v}</td></tr>`).join('')

  const tests: any[] = form.testRequests ?? []
  const testRows = tests.map((t: any) => `<tr>
    <td>${t.testName ?? t.technique ?? '—'}</td>
    <td>${t.sampleLabel ?? '—'}</td>
    <td>${t.specification ?? '—'}</td>
    <td>${statusBadge(t.status)}</td>
  </tr>`).join('')

  const body = `
    <div class="header-block">
      <div>
        <div class="label">${company}</div>
        <h1>Analytical Request (ATR)</h1>
        <div style="color:${SLATE};font-size:9pt;margin-top:4px">${form.arNo ?? 'Draft'}</div>
      </div>
      <img src="${qr}" width="80" height="80"/>
    </div>
    <table class="meta-table"><tbody>${metaRows}</tbody></table>
    <h2>Test Requests</h2>
    <table>
      <thead><tr><th>Test / Technique</th><th>Sample Label</th><th>Specification</th><th>Status</th></tr></thead>
      <tbody>${testRows || '<tr><td colspan="4">No test requests</td></tr>'}</tbody>
    </table>`
  return wrap(`ATR ${form.arNo ?? ''}`, body)
}

