// ── ARD Experiment Report ─────────────────────────────────────────────────────
export function ardExperimentReportHtml(
  exp: any, notebook: any, project: any,
  creatorName: string, company = 'Laurus Labs'
): string {
  // exp.sections is stored as an object keyed by section id (not an array) —
  // calling .map on it threw and made every PDF export fail silently (caught
  // upstream and surfaced as a generic 500).
  const rawSections = notebook?.templateSnapshot?.sections ?? exp.sections ?? []
  const sections: any[] = Array.isArray(rawSections) ? rawSections : Object.values(rawSections || {})

  function renderSection(sec: any): string {
    const kind = sec.type ?? sec.kind ?? ''
    const title = sec.title ?? sec.label ?? kind
    const value = sec.value ?? sec.data ?? null

    if (kind === 'richtext' || kind === 'conclusion' || kind === 'disposition' || kind === 'observations') {
      return `<div class="section-title">${title}</div>
        <div style="padding:6px;border:1px solid #e2e8f0;margin-bottom:8px;font-size:9pt">${value ?? ''}</div>`
    }
    if (kind === 'table' && Array.isArray(value)) {
      const headers = value[0] ? Object.keys(value[0]) : []
      const thRow = headers.map(h => `<th>${h}</th>`).join('')
      const rows = value.map((row: any) =>
        `<tr>${headers.map(h => `<td>${row[h] ?? ''}</td>`).join('')}</tr>`
      ).join('')
      return `<div class="section-title">${title}</div>
        <table><thead><tr>${thRow}</tr></thead><tbody>${rows}</tbody></table>`
    }
    if (kind === 'params' && typeof value === 'object' && value) {
      const rows = Object.entries(value).map(([k, v]) =>
        `<tr><td class="label">${k}</td><td>${v ?? ''}</td></tr>`
      ).join('')
      return `<div class="section-title">${title}</div>
        <table class="meta-table"><tbody>${rows}</tbody></table>`
    }
    if (value !== null && value !== undefined) {
      return `<div class="section-title">${title}</div>
        <div style="padding:6px 8px;border:1px solid #e2e8f0;margin-bottom:8px">${String(value)}</div>`
    }
    return ''
  }

  const sectionHtml = sections.map(renderSection).join('')
  const meta = [
    ['Project', project?.name ?? project?.code ?? '—'],
    ['Notebook', notebook?.code ?? notebook?.title ?? '—'],
    ['Experiment Code', exp.code ?? exp.id ?? '—'],
    ['Title', exp.title ?? '—'],
    ['Status', statusBadge(exp.status)],
    ['Submitted By', creatorName],
    ['Submitted At', exp.submittedAt ? new Date(exp.submittedAt).toLocaleDateString('en-IN') : '—'],
    ['Approved By', exp.approvedBy ?? '—'],
    ['Approved At', exp.approvedAt ? new Date(exp.approvedAt).toLocaleDateString('en-IN') : '—'],
    ['Generated', new Date().toLocaleString('en-IN')],
  ]
  const metaRows = meta.map(([k, v]) => `<tr><td class="label">${k}</td><td>${v}</td></tr>`).join('')

  const body = `
    <div class="header-block">
      <div><div class="label">${company}</div><h1>Experiment Report</h1>
        <div style="color:${SLATE};font-size:9pt;margin-top:4px">${exp.code ?? exp.id ?? '—'} · ${exp.title ?? ''}</div>
      </div>
    </div>
    <table class="meta-table"><tbody>${metaRows}</tbody></table>
    ${sectionHtml}`
  return wrap(`Experiment Report ${exp.code ?? ''}`, body)
}

