// ── ARD Report (generic — wraps tabular report data) ──────────────────────────
export function ardReportHtml(reportName: string, headers: string[], rows: any[][], params: Record<string, string>, company = 'Laurus Labs'): string {
  const paramRows = Object.entries(params).filter(([, v]) => v)
    .map(([k, v]) => `<tr><td class="label">${k}</td><td>${v}</td></tr>`).join('')

  const thRow = headers.map(h => `<th>${h}</th>`).join('')
  const dataRows = rows.map(r =>
    `<tr>${r.map(c => `<td>${c ?? '—'}</td>`).join('')}</tr>`
  ).join('')

  const body = `
    <div class="header-block">
      <div><div class="label">${company}</div><h1>${reportName}</h1>
        <div style="color:${SLATE};font-size:9pt;margin-top:4px">Generated ${new Date().toLocaleString('en-IN')}</div>
      </div>
    </div>
    ${paramRows ? `<table class="meta-table"><tbody>${paramRows}</tbody></table>` : ''}
    <table>
      <thead><tr>${thRow}</tr></thead>
      <tbody>${dataRows || `<tr><td colspan="${headers.length}">No data</td></tr>`}</tbody>
    </table>`
  return wrap(reportName, body)
}

// ── ADC/CGT Experiment Report (replaces python-docx) ─────────────────────────
export function adcExperimentReportHtml(
  exp: any, notebook: any, project: any,
  approverName: string, submitterName: string, company = 'Laurus Labs'
): string {
  const sections: any[] = exp.templateSnapshot?.sections ?? notebook?.templateSnapshot?.sections ?? []

  function renderSection(sec: any): string {
    const kind = sec.type ?? sec.kind ?? 'field'
    const title = sec.title ?? sec.label ?? kind

    if (['richtext', 'text', 'observations', 'conclusion', 'disposition'].includes(kind)) {
      return `<div class="section-title">${title}</div>
        <div style="padding:8px;border:1px solid #e2e8f0;margin-bottom:8px">${sec.value ?? ''}</div>`
    }
    if (kind === 'table' && Array.isArray(sec.value)) {
      const headers = sec.value[0] ? Object.keys(sec.value[0]) : []
      const thRow = headers.map((h: string) => `<th>${h}</th>`).join('')
      const rows = sec.value.map((row: any) =>
        `<tr>${headers.map((h: string) => `<td>${row[h] ?? ''}</td>`).join('')}</tr>`
      ).join('')
      return `<div class="section-title">${title}</div>
        <table><thead><tr>${thRow}</tr></thead><tbody>${rows}</tbody></table>`
    }
    if (kind === 'js_sheet') {
      const fields: any[] = sec.fieldValues ?? []
      const rows = fields.map((f: any) =>
        `<tr><td class="label">${f.label ?? f.key ?? '—'}</td><td>${f.value ?? ''}</td></tr>`
      ).join('')
      return `<div class="section-title">${title}</div>
        <table class="meta-table"><tbody>${rows || '<tr><td colspan="2">No fields</td></tr>'}</tbody></table>`
    }
    return ''
  }

  const meta = [
    ['Project', project?.name ?? project?.projectName ?? '—'],
    ['Notebook', notebook?.code ?? notebook?.title ?? '—'],
    ['Experiment Code', exp.code ?? exp.experimentCode ?? '—'],
    ['Title', exp.title ?? '—'],
    ['Status', statusBadge(exp.status)],
    ['Submitted By', submitterName],
    ['Submitted At', exp.submittedAt ? new Date(exp.submittedAt).toLocaleDateString('en-IN') : '—'],
    ['Approved By', approverName],
    ['Approved At', exp.approvedAt ? new Date(exp.approvedAt).toLocaleDateString('en-IN') : '—'],
    ['Generated', new Date().toLocaleString('en-IN')],
  ]
  const metaRows = meta.map(([k, v]) => `<tr><td class="label">${k}</td><td>${v}</td></tr>`).join('')
  const sectionHtml = sections.map(renderSection).join('')

  const body = `
    <div class="header-block">
      <div><div class="label">${company}</div><h1>Experiment Report</h1>
        <div style="color:${SLATE};font-size:9pt;margin-top:4px">${exp.code ?? exp.experimentCode ?? '—'} · ${exp.title ?? ''}</div>
      </div>
    </div>
    <table class="meta-table"><tbody>${metaRows}</tbody></table>
    ${sectionHtml}`
  return wrap(`Experiment Report ${exp.code ?? ''}`, body)
}
